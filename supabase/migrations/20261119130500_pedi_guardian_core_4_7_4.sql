create table if not exists public.groups (
  id bigint generated by default as identity primary key,
  telegram_chat_id bigint not null unique,
  title text not null default '',
  settings jsonb not null default '{}'::jsonb,
  owner_user_id bigint,
  warning_limit integer not null default 3 check (warning_limit between 1 and 100),
  created_at timestamptz not null default now()
);

create table if not exists public.members (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.groups(id) on delete cascade,
  telegram_user_id bigint not null,
  role text not null default 'MEMBER' check (role in ('RESTRICTED','MEMBER','HELPER','MODERATOR','ADMIN','SENIOR_ADMIN','GROUP_OWNER','BOT_OWNER')),
  created_at timestamptz not null default now(),
  unique (group_id, telegram_user_id)
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.groups(id) on delete cascade,
  actor_user_id bigint not null,
  action text not null,
  target_user_id bigint,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.telegram_updates (
  update_id bigint primary key,
  received_at timestamptz not null default now()
);

create table if not exists public.warnings (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.groups(id) on delete cascade,
  telegram_user_id bigint not null,
  reason text not null default 'manual',
  issued_by bigint not null,
  created_at timestamptz not null default now()
);

create table if not exists public.locks (
  group_id bigint not null references public.groups(id) on delete cascade,
  lock_type text not null,
  enabled boolean not null default true,
  action text not null default 'delete',
  updated_at timestamptz not null default now(),
  primary key (group_id, lock_type)
);

create table if not exists public.group_access (
  group_id bigint primary key references public.groups(id) on delete cascade,
  access_until timestamptz,
  is_active boolean not null default true,
  last_extended_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.voice_order_requests (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.groups(id) on delete cascade,
  requested_by bigint not null,
  count integer not null check (count between 1 and 200),
  status text not null default 'PENDING' check (status in ('PENDING','CLAIMED','DONE','FAILED')),
  worker_id text,
  result jsonb,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.voice_worker_heartbeats (
  worker_id text primary key,
  status text not null default 'IDLE',
  details jsonb not null default '{}'::jsonb,
  last_seen_at timestamptz not null default now()
);

create table if not exists public.voice_call_presence_snapshots (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.groups(id) on delete cascade,
  user_id bigint not null,
  display_name text not null,
  observed_at timestamptz not null default now()
);

create index if not exists audit_logs_group_created_idx on public.audit_logs (group_id, created_at desc);
create index if not exists warnings_group_user_idx on public.warnings (group_id, telegram_user_id, created_at desc);
create index if not exists voice_order_requests_pending_idx on public.voice_order_requests (status, created_at);
create index if not exists voice_presence_group_observed_idx on public.voice_call_presence_snapshots (group_id, observed_at desc);

create or replace function public.claim_voice_order_request(p_id bigint, p_worker_id text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  claimed integer := 0;
begin
  update public.voice_order_requests
     set status = 'CLAIMED', worker_id = p_worker_id
   where id = p_id and status = 'PENDING';
  get diagnostics claimed = row_count;
  return claimed = 1;
end;
$$;

revoke execute on function public.claim_voice_order_request(bigint, text) from public, anon, authenticated;
grant execute on function public.claim_voice_order_request(bigint, text) to service_role;

